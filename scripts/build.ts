/**
 * Builds the package:
 *   1. Tailwind compiles src/widget.css (material's stylesheet + the widget base) to text.
 *   2. Bun bundles the custom element to a hashed ESM file: dist/widget.<hash>.js.
 *   3. Bun bundles the loader to a classic script (IIFE): dist/loader.js, with the
 *      hashed file name baked in.
 * dist/manifest.json names both; the UI serves the hashed file with a long cache and
 * loader.js with a short one (plan section 13).
 */
import { copyFile, mkdir, rm, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { remToPx } from "./rem-to-px";

const root = join(import.meta.dir, "..");
const dist = join(root, "dist");
const generated = join(root, "src/generated");

async function run(cmd: string[]) {
  const proc = Bun.spawn(cmd, {
    cwd: root,
    stdout: "inherit",
    stderr: "inherit",
  });
  const code = await proc.exited;
  if (code !== 0) throw new Error(`${cmd.join(" ")} exited with ${code}`);
}

async function build() {
  await rm(dist, { recursive: true, force: true });
  await mkdir(dist, { recursive: true });
  await mkdir(generated, { recursive: true });

  const cssFile = join(dist, ".widget.css");
  await run([
    "bunx",
    "@tailwindcss/cli",
    "-i",
    "src/widget.css",
    "-o",
    cssFile,
    "--minify",
  ]);
  const css = remToPx(await Bun.file(cssFile).text());
  await writeFile(
    join(generated, "widget-css.ts"),
    `// Generated by scripts/build.ts: do not edit.\nexport default ${JSON.stringify(css)};\n`,
  );
  await rm(cssFile);

  const esm = await Bun.build({
    entrypoints: [join(root, "src/index.ts")],
    outdir: dist,
    target: "browser",
    format: "esm",
    minify: true,
    naming: "widget.[hash].[ext]",
    define: { "process.env.NODE_ENV": '"production"' },
  });
  if (!esm.success) throw new Error(esm.logs.join("\n"));
  const entry = esm.outputs.find((o) => o.kind === "entry-point");
  if (!entry) throw new Error("no ESM entry output");
  const widgetFile = entry.path.split("/").pop() as string;
  // The npm entry keeps a stable name beside the hashed one.
  await copyFile(entry.path, join(dist, "index.js"));

  const loader = await Bun.build({
    entrypoints: [join(root, "src/loader.ts")],
    outdir: dist,
    target: "browser",
    format: "iife",
    minify: true,
    naming: "loader.js",
    define: { __WIDGET_FILE__: JSON.stringify(widgetFile) },
  });
  if (!loader.success) throw new Error(loader.logs.join("\n"));

  await writeFile(
    join(dist, "manifest.json"),
    `${JSON.stringify({ loader: "loader.js", widget: widgetFile }, null, 2)}\n`,
  );
  console.log(`built dist/loader.js and dist/${widgetFile}`);
}

await build();
