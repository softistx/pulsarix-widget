/**
 * Builds the package:
 *   1. The widget's stylesheet, as one text: the utilities Tailwind generates for the widget's own
 *      classes (src/widget.css; its @property values copied to plain declarations), then
 *      material's embed.css (already px, @property values as plain declarations, tokens on
 *      :host), then the widget base (src/base.css).
 *      The editor's stylesheet (material's image-editor.css) becomes src/generated/editor-css.ts,
 *      imported only by the lazy editor chunk.
 *   2. Bun bundles the custom element to a hashed ESM file, dist/widget.<hash>.js, with its lazy
 *      chunks (dist/<name>.<hash>.js, listed in the manifest); dist/index.js is an unsplit copy for npm.
 *   3. tsc emits the declarations of the npm entry to dist/types.
 *   4. Bun bundles the server helper (src/server.ts) to dist/server.js, apart from the widget.
 *   5. Bun bundles the loader to a classic script (IIFE): dist/loader.js, with the
 *      hashed file name baked in.
 * dist/manifest.json names both; the UI serves the hashed file with a long cache and
 * loader.js with a short one (plan section 13).
 */
import { mkdir, rm, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { withPropertyFallbacks } from "@softistx/material/embed-css";

const root = join(import.meta.dir, "..");
const dist = join(root, "dist");
const generated = join(root, "src/generated");
const embedCss = Bun.resolveSync("@softistx/material/embed.css", root);
const editorCssFile = Bun.resolveSync(
  "@softistx/material/image-editor.css",
  root,
);

async function run(cmd: string[]) {
  const proc = Bun.spawn(cmd, {
    cwd: root,
    stdout: "inherit",
    stderr: "inherit",
  });
  const code = await proc.exited;
  if (code !== 0) throw new Error(`${cmd.join(" ")} exited with ${code}`);
}

async function build() {
  await rm(dist, { recursive: true, force: true });
  await mkdir(dist, { recursive: true });
  await mkdir(generated, { recursive: true });

  const cssFile = join(dist, ".widget.css");
  await run([
    "bunx",
    "@tailwindcss/cli",
    "-i",
    "src/widget.css",
    "-o",
    cssFile,
    "--minify",
  ]);
  // The widget's utilities are `@layer utilities` (widget.css declares the layer order), so
  // they no longer beat material's layered rules by being unlayered. They go before embed.css:
  // within the layer, a later plain `.flex-col` would beat embed.css's `sm:flex-row` (same
  // specificity, later wins).
  // withPropertyFallbacks declares `nxgt-property-initial` first, the lowest layer.
  const css = [
    withPropertyFallbacks(await Bun.file(cssFile).text()),
    await Bun.file(embedCss).text(),
    await Bun.file(join(root, "src/base.css")).text(),
  ].join("\n");
  await writeFile(
    join(generated, "widget-css.ts"),
    `// Generated by scripts/build.ts: do not edit.\nexport default ${JSON.stringify(css)};\n`,
  );
  await rm(cssFile);
  // The editor's stylesheet (shadow-root-ready, px units) rides in the lazy editor chunk as text.
  await writeFile(
    join(generated, "editor-css.ts"),
    `// Generated by scripts/build.ts: do not edit.\nexport default ${JSON.stringify(
      await Bun.file(editorCssFile).text(),
    )};\n`,
  );

  const esm = await Bun.build({
    entrypoints: [join(root, "src/index.ts")],
    outdir: dist,
    target: "browser",
    format: "esm",
    minify: true,
    // Code splitting: a lazy `import()` becomes a chunk beside the entry, named by hash.
    splitting: true,
    naming: {
      entry: "widget.[hash].[ext]",
      chunk: "[name].[hash].[ext]",
      asset: "[name].[hash].[ext]",
    },
    define: { "process.env.NODE_ENV": '"production"' },
  });
  if (!esm.success) throw new Error(esm.logs.join("\n"));
  const entry = esm.outputs.find((o) => o.kind === "entry-point");
  if (!entry) throw new Error("no ESM entry output");
  const widgetFile = entry.path.split("/").pop() as string;
  const chunks = esm.outputs
    .filter((o) => o.kind === "chunk")
    .map((o) => o.path.split("/").pop() as string)
    .sort();
  // The npm entry is one self-contained file (the package ships `dist/index.js` alone), so it is
  // a second, unsplit bundle under a stable name.
  const single = await Bun.build({
    entrypoints: [join(root, "src/index.ts")],
    outdir: dist,
    target: "browser",
    format: "esm",
    minify: true,
    splitting: false,
    naming: "index.js",
    define: { "process.env.NODE_ENV": '"production"' },
  });
  if (!single.success) throw new Error(single.logs.join("\n"));

  // The server helper (`@softistx/pulsarix-widget/server`): its own Node-targeted bundle, with
  // `node:crypto` left external. Nothing in the widget or the loader imports it.
  const server = await Bun.build({
    entrypoints: [join(root, "src/server.ts")],
    outdir: dist,
    target: "node",
    format: "esm",
    minify: false,
    naming: "server.js",
    external: ["node:crypto"],
  });
  if (!server.success) throw new Error(server.logs.join("\n"));

  const loader = await Bun.build({
    entrypoints: [join(root, "src/loader.ts")],
    outdir: dist,
    target: "browser",
    format: "iife",
    minify: true,
    naming: "loader.js",
    define: { __WIDGET_FILE__: JSON.stringify(widgetFile) },
  });
  if (!loader.success) throw new Error(loader.logs.join("\n"));

  // Declarations for the npm entry (`bun check` emits nothing): dist/types/index.d.ts.
  await run([join(root, "node_modules/.bin/tsc"), "-p", "tsconfig.build.json"]);

  await writeFile(
    join(dist, "manifest.json"),
    `${JSON.stringify({ loader: "loader.js", widget: widgetFile, chunks }, null, 2)}\n`,
  );
  console.log(`built dist/loader.js and dist/${widgetFile}`);
}

await build();
